export function AuthorTile({
  active,
  sortOrder,
  entranceState,
}: {
  active: boolean;
  sortOrder: number;
  entranceState?: "visible" | null;
}) {
  const cellRef = useRef<HTMLDivElement>(null);
  const [userPaused, setUserPaused] = useState(false);
  const [offscreen, setOffscreen] = useState(false);

  useEffect(() => {
    const node = cellRef.current;
    if (!node) return;
    const observer = new IntersectionObserver(([entry]) => {
      setOffscreen(!entry.isIntersecting);
    });
    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  const motionOff = userPaused || offscreen;

  return (
    <div
      ref={cellRef}
      className={`tile-slot author-cell${motionOff ? " motion-off" : ""}`}
      data-categories="about"
      data-active={active}
      data-grid-order={sortOrder}
      data-entrance={entranceState || undefined}
      inert={!active || undefined}
    >
      <div className="author-tile">
        <div className="author-face" data-continuous-corners="">
          <p className="author-line">
            {AUTHOR_LABEL.replace("Grok Bot", "Grok\u00A0Bot")}
          </p>
          <svg
            className="author-ul"
            viewBox="0 0 160 14"
            preserveAspectRatio="none"
            aria-hidden="true"
            focusable="false"
          >
            <path d="M3 9 C 30 3, 60 12, 90 7 S 140 4, 157 8" />
          </svg>
          <div className="author-bots" aria-hidden="true">
            {BOTS.map((bot) => (
              <svg
                key={bot.id}
                className={`author-bot${bot.heightClass ? ` ${bot.heightClass}` : ""}`}
                viewBox={bot.viewBox}
                style={
                  {
                    "--dur": bot.dur,
                    "--blink": bot.blink,
                  } as CSSProperties
                }
                focusable="false"
              >
                <path
                  transform={bot.transform}
                  fill={bot.fill}
                  fillRule="evenodd"
                  d={bot.body}
                />
                <g transform={bot.transform}>
                  <path className="lid" fill={bot.fill} d={bot.lid} />
                </g>
              </svg>
            ))}
          </div>
        </div>
      </div>
      <button
        type="button"
        className="author-pause"
        aria-pressed={userPaused}
        aria-label="Pause animation"
        onClick={() => setUserPaused((paused) => !paused)}
      >
        {userPaused ? <PlayIcon /> : <PauseIcon />}
      </button>
    </div>
  );
}
